using System;
using System.Collections.Generic;
using System.Globalization;
using System.Linq;
using System.Text;
using System.Threading;

using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;

namespace XUnitAssured.SourceGenerators;

/// <summary>
/// Gera, para cada método público de um builder de validação, o mesmo método sobre a
/// <c>Task</c> do builder, para as asserções encadearem antes do <c>await</c>:
/// <c>await Given()...ExecuteAsync().AssertTopic("orders")</c>.
///
/// <para>
/// O HTTP tem essas extensões escritas à mão (<c>HttpValidationTaskExtensions</c>), com um
/// teste que falha quando um método do builder fica sem a sua. O builder do Playwright tem 181
/// métodos: escrever e manter cada um à mão seria uma segunda cópia de toda a superfície, que
/// divergiria da primeira no primeiro método novo. Gerado, um método novo no builder ganha a
/// extensão na mesma compilação.
/// </para>
///
/// <para>
/// Uso: uma classe estática parcial marcada com o atributo, apontando o builder.
/// <code>
/// [ExtensoesDeTask(typeof(KafkaValidationBuilder))]
/// public static partial class KafkaValidationTaskExtensions { }
/// </code>
/// </para>
/// </summary>
[Generator(LanguageNames.CSharp)]
public sealed class ExtensoesDeTaskGenerator : IIncrementalGenerator
{
	private const string NomeDoAtributo = "XUnitAssured.Geracao.ExtensoesDeTaskAttribute";

	private const string FonteDoAtributo = """
		// <auto-generated/>
		namespace XUnitAssured.Geracao
		{
			/// <summary>
			/// Gera, na classe estática parcial marcada, um método sobre <c>Task&lt;TBuilder&gt;</c> para
			/// cada método público do builder: as asserções encadeiam antes do <c>await</c>.
			/// </summary>
			[global::System.AttributeUsage(global::System.AttributeTargets.Class, Inherited = false)]
			internal sealed class ExtensoesDeTaskAttribute : global::System.Attribute
			{
				/// <summary>Marca a classe que recebe as extensões do builder.</summary>
				/// <param name="builder">O builder de validação</param>
				public ExtensoesDeTaskAttribute(global::System.Type builder) => Builder = builder;

				/// <summary>O builder de validação.</summary>
				public global::System.Type Builder { get; }
			}
		}
		""";

	// Com global:: e com o ? das referências anuláveis: o código gerado compila igual em qualquer
	// namespace e não perde a anotação de nulo do original.
	private static readonly SymbolDisplayFormat Formato = SymbolDisplayFormat.FullyQualifiedFormat
		.AddMiscellaneousOptions(SymbolDisplayMiscellaneousOptions.IncludeNullableReferenceTypeModifier);

	/// <inheritdoc />
	public void Initialize(IncrementalGeneratorInitializationContext context)
	{
		context.RegisterPostInitializationOutput(c => c.AddSource("ExtensoesDeTaskAttribute.g.cs", FonteDoAtributo));

		var alvos = context.SyntaxProvider.ForAttributeWithMetadataName(
			NomeDoAtributo,
			static (no, _) => no is ClassDeclarationSyntax,
			static (ctx, cancelamento) => Montar(ctx, cancelamento));

		context.RegisterSourceOutput(alvos, static (saida, arquivo) =>
		{
			if (arquivo != null)
				saida.AddSource(arquivo.Nome, arquivo.Codigo);
		});
	}

	private static ArquivoGerado? Montar(GeneratorAttributeSyntaxContext ctx, CancellationToken cancelamento)
	{
		if (ctx.TargetSymbol is not INamedTypeSymbol classe
			|| ctx.Attributes.FirstOrDefault()?.ConstructorArguments.FirstOrDefault().Value is not INamedTypeSymbol builder)
			return null;

		var b = builder.ToDisplayString(Formato);
		var codigo = new StringBuilder();
		codigo.AppendLine("// <auto-generated/>");
		codigo.AppendLine("#nullable enable");
		codigo.AppendLine();
		if (!classe.ContainingNamespace.IsGlobalNamespace)
			codigo.AppendLine($"namespace {classe.ContainingNamespace.ToDisplayString()};").AppendLine();

		codigo.AppendLine($"static partial class {classe.Name}");
		codigo.AppendLine("{");
		codigo.AppendLine($"\tprivate static global::System.Runtime.CompilerServices.ConfiguredTaskAwaitable<{b}> Pronto(global::System.Threading.Tasks.Task<{b}> chain) =>");
		codigo.AppendLine("\t\t(chain ?? throw new global::System.ArgumentNullException(nameof(chain))).ConfigureAwait(false);");

		foreach (var metodo in Metodos(builder))
		{
			cancelamento.ThrowIfCancellationRequested();
			codigo.AppendLine();
			Escrever(codigo, metodo, builder, b);
		}

		codigo.AppendLine("}");
		return new ArquivoGerado($"{classe.ToDisplayString().Replace('<', '_').Replace('>', '_')}.g.cs", codigo.ToString());
	}

	/// <summary>
	/// Os métodos públicos de instância do builder e de suas bases, o mais derivado primeiro: um
	/// método escondido com <c>new</c> ou sobrescrito aparece uma vez, na forma do builder.
	/// Ficam de fora os que têm parâmetro <c>out</c> ou <c>ref</c>, que um método assíncrono não tem.
	/// </summary>
	private static IEnumerable<IMethodSymbol> Metodos(INamedTypeSymbol builder)
	{
		var vistos = new HashSet<string>();

		for (var tipo = builder; tipo != null && tipo.SpecialType != SpecialType.System_Object; tipo = tipo.BaseType)
		{
			foreach (var metodo in tipo.GetMembers().OfType<IMethodSymbol>())
			{
				if (metodo.MethodKind != MethodKind.Ordinary || metodo.IsStatic
					|| metodo.DeclaredAccessibility != Accessibility.Public
					|| metodo.Parameters.Any(p => p.RefKind != RefKind.None))
					continue;

				var assinatura = $"{metodo.Name}`{metodo.Arity}({string.Join(",", metodo.Parameters.Select(p => p.Type.ToDisplayString()))})";
				if (vistos.Add(assinatura))
					yield return metodo;
			}
		}
	}

	private static void Escrever(StringBuilder codigo, IMethodSymbol metodo, INamedTypeSymbol builder, string b)
	{
		var retorno = metodo.ReturnType;
		var devolveOBuilder = SymbolEqualityComparer.Default.Equals(retorno, builder);

		// Um método herdado do builder genérico devolve o próprio objeto como o tipo base; na
		// extensão a cadeia continua no builder do protocolo, como o HTTP faz com new.
		var devolveABase = !devolveOBuilder && EBaseDe(retorno, builder);

		var tipoDeRetorno = metodo.ReturnsVoid ? "global::System.Threading.Tasks.Task"
			: devolveOBuilder || devolveABase ? $"global::System.Threading.Tasks.Task<{b}>"
			: $"global::System.Threading.Tasks.Task<{retorno.ToDisplayString(Formato)}>";

		var parametros = string.Join(", ", metodo.Parameters.Select(Parametro));
		var argumentos = string.Join(", ", metodo.Parameters.Select(p => Nome(p.Name)));
		var genericos = metodo.TypeParameters.Length == 0 ? "" : $"<{string.Join(", ", metodo.TypeParameters.Select(t => t.Name))}>";
		var chamada = $"{Nome(metodo.Name)}{genericos}({argumentos})";

		var id = metodo.OriginalDefinition.GetDocumentationCommentId();
		if (id != null)
			codigo.AppendLine($"\t/// <inheritdoc cref=\"{id}\"/>");

		codigo.Append($"\tpublic static async {tipoDeRetorno} {Nome(metodo.Name)}{genericos}(this global::System.Threading.Tasks.Task<{b}> chain");
		codigo.Append(parametros.Length == 0 ? ")" : $", {parametros})");
		codigo.Append(Restricoes(metodo));
		codigo.AppendLine();

		if (!devolveABase)
		{
			codigo.AppendLine($"\t\t=> (await Pronto(chain)).{chamada};");
			return;
		}

		codigo.AppendLine("\t{");
		codigo.AppendLine("\t\tvar atual = await Pronto(chain);");
		codigo.AppendLine($"\t\tatual.{chamada};");
		codigo.AppendLine("\t\treturn atual;");
		codigo.AppendLine("\t}");
	}

	private static bool EBaseDe(ITypeSymbol talvezBase, INamedTypeSymbol tipo)
	{
		for (var atual = tipo.BaseType; atual != null; atual = atual.BaseType)
		{
			if (SymbolEqualityComparer.Default.Equals(atual, talvezBase))
				return true;
		}

		return false;
	}

	private static string Parametro(IParameterSymbol p)
	{
		var texto = $"{(p.IsParams ? "params " : "")}{p.Type.ToDisplayString(Formato)} {Nome(p.Name)}";
		return p.HasExplicitDefaultValue ? $"{texto} = {Literal(p.ExplicitDefaultValue, p.Type)}" : texto;
	}

	private static string Restricoes(IMethodSymbol metodo)
	{
		var texto = new StringBuilder();

		foreach (var t in metodo.TypeParameters)
		{
			var partes = new List<string>();
			if (t.HasReferenceTypeConstraint)
				partes.Add(t.ReferenceTypeConstraintNullableAnnotation == NullableAnnotation.Annotated ? "class?" : "class");
			if (t.HasUnmanagedTypeConstraint)
				partes.Add("unmanaged");
			else if (t.HasValueTypeConstraint)
				partes.Add("struct");
			if (t.HasNotNullConstraint)
				partes.Add("notnull");
			partes.AddRange(t.ConstraintTypes.Select(c => c.ToDisplayString(Formato)));
			if (t.HasConstructorConstraint)
				partes.Add("new()");

			if (partes.Count > 0)
				texto.Append($" where {t.Name} : {string.Join(", ", partes)}");
		}

		return texto.ToString();
	}

	private static string Literal(object? valor, ITypeSymbol tipo)
	{
		if (valor == null)
			return tipo.IsValueType && tipo.OriginalDefinition.SpecialType != SpecialType.System_Nullable_T ? "default" : "null";

		if (tipo.TypeKind == TypeKind.Enum)
			return $"({tipo.ToDisplayString(Formato)})({Convert.ToString(valor, CultureInfo.InvariantCulture)})";

		return valor switch
		{
			string s => SymbolDisplay.FormatLiteral(s, quote: true),
			char c => SymbolDisplay.FormatLiteral(c, quote: true),
			bool v => v ? "true" : "false",
			float f => f.ToString("R", CultureInfo.InvariantCulture) + "F",
			double d => d.ToString("R", CultureInfo.InvariantCulture) + "D",
			decimal m => m.ToString(CultureInfo.InvariantCulture) + "M",
			long l => l.ToString(CultureInfo.InvariantCulture) + "L",
			ulong u => u.ToString(CultureInfo.InvariantCulture) + "UL",
			uint u => u.ToString(CultureInfo.InvariantCulture) + "U",
			_ => Convert.ToString(valor, CultureInfo.InvariantCulture)!
		};
	}

	private static string Nome(string nome) =>
		SyntaxFacts.GetKeywordKind(nome) != SyntaxKind.None ? "@" + nome : nome;

	/// <summary>O arquivo gerado. Igualdade por valor, para o gerador incremental não refazer à toa.</summary>
	private sealed class ArquivoGerado : IEquatable<ArquivoGerado>
	{
		public ArquivoGerado(string nome, string codigo)
		{
			Nome = nome;
			Codigo = codigo;
		}

		public string Nome { get; }

		public string Codigo { get; }

		public bool Equals(ArquivoGerado? outro) => outro != null && Nome == outro.Nome && Codigo == outro.Codigo;

		public override bool Equals(object? obj) => Equals(obj as ArquivoGerado);

		public override int GetHashCode() => Nome.GetHashCode() ^ Codigo.GetHashCode();
	}
}
